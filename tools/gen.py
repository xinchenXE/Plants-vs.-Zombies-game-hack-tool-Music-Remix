#!/usr/bin/env python3
"""把 XM 模块和查表数据生成为 C 头文件。

输出：
  src/mod_data.h  —— 整个 XM 文件原样内嵌（运行期自己解析）
  src/tables.h    —— 音符步进表（16.16）、乐器倍率表、周期常数等
"""
import sys, os, struct

SRC = os.path.join(os.path.dirname(__file__), '..', 'funky_stars_rmx_ror.xm')
OUT = os.path.join(os.path.dirname(__file__), '..', 'src')


def read_instruments(d):
    """返回每个乐器的 (relnote, fine)，按乐器号索引；空乐器给 0,0。"""
    o = 17 + 20 + 1 + 20 + 2 + 4
    vals = struct.unpack_from('<8H', d, o)
    hsize = struct.unpack_from('<I', d, 17 + 20 + 1 + 20 + 2)[0]
    songlen, restart, ch, npat, ninst = vals[:5]
    o += 16 + 256 + (hsize - 276 if hsize > 276 else 0)
    for _ in range(npat):
        ph = struct.unpack_from('<I', d, o)[0]
        sz = struct.unpack_from('<H', d, o + 7)[0]
        o += ph + sz
    out = []
    for _ in range(ninst):
        sz = struct.unpack_from('<I', d, o)[0]
        ns = struct.unpack_from('<H', d, o + 27)[0]
        rel = fine = 0
        if ns:
            so = o + sz
            rel = struct.unpack_from('<b', d, so + 16)[0]
            fine = struct.unpack_from('<b', d, so + 13)[0]
        out.append((rel, fine))
        # 跳过采样数据
        p = o + sz
        if ns:
            shs = struct.unpack_from('<I', d, o + 29)[0]
            lens = []
            for _ in range(ns):
                lens.append(struct.unpack_from('<I', d, p)[0])
                p += shs
            p += sum(lens)
        o = p
    return out


def main():
    d = open(SRC, 'rb').read()
    os.makedirs(OUT, exist_ok=True)

    # ---- 模块原始字节 ----
    lines = []
    for i in range(0, len(d), 20):
        lines.append('    ' + ','.join('0x%02x' % b for b in d[i:i+20]) + ',')
    h = ('/* Funky Stars RMX (ROR keygen version) - original XM module\n'
         ' * %d bytes, MD5 c08b50657b5f1cc74eb72638c276a588\n'
         ' * by ____CHROMAX____ 2002, original tune by Quazar / Sanxion 1996\n'
         ' * Embedded verbatim; the player parses it at startup. */\n'
         '#pragma once\n\n'
         'static const unsigned char g_mod[] = {\n%s\n};\n'
         '#define MOD_SIZE %d\n' % (len(d), '\n'.join(lines), len(d)))
    open(os.path.join(OUT, 'mod_data.h'), 'w', encoding='utf-8').write(h)

    # ---- 音符步进表：8363Hz 基准，16.16 定点 ----
    tab = []
    for n in range(1, 97):
        f = 8363.0 * 2.0 ** ((n - 49) / 12.0)
        tab.append(round(f / 44100.0 * 65536.0))
    # ---- 乐器倍率：2^((relnote + fine/128)/12) ----
    insts = read_instruments(d)
    mult = [round(2.0 ** ((rel + fine / 128.0) / 12.0) * 65536.0) for rel, fine in insts]
    # 周期常数 C：step = C*mult/P，C = 8363*1712*65536/44100
    C = round(8363 * 1712 * 65536 / 44100)
    # ---- 每乐器步进常数 K：step = K / period（32 位除法，避免 __udivdi3） ----
    K = [round(14317456 * 2.0 ** ((rel + fine / 128.0) / 12.0) * 65536.0 / 44100.0) for rel, fine in insts]
    # ---- Amiga 周期表 ----
    per = [int(round(1712.0 * 2.0 ** ((49.0 - n) / 12.0))) for n in range(1, 97)]

    t = ['/* generated by tools/gen.py - do not edit */', '#pragma once', '',
          '/* step(16.16) = g_instK[inst] / period */',
          'static const unsigned int g_instK[%d] = {' % len(K)]
    for i in range(0, len(K), 8):
        t.append('    ' + ','.join(str(x) for x in K[i:i+8]) + ',')
    t += ['};', '',
          '/* Amiga period per note (C-4 = 1712 -> 8363 Hz), index = note-1 */',
          'static const unsigned short g_period[96] = {']
    for i in range(0, 96, 12):
        t.append('    ' + ','.join(str(x) for x in per[i:i+12]) + ',')
    t += ['};', '']
    open(os.path.join(OUT, 'tables.h'), 'w', encoding='utf-8').write('\n'.join(t))

    print('module %d bytes, %d instruments, PERIOD_C=%d' % (len(d), len(mult), C))
    print('noteTab[48]=%d (C-4), instMul[0]=%d' % (tab[48], mult[0]))


if __name__ == '__main__':
    main()
